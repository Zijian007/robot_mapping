def patch_rpath(path, replacement):
    """Replace an existing ELF64 LE path in-place, using transitive DT_RPATH.

    Fail closed when the input has no reserved slot or does not match the
    supported layout. Never modify the original build: callers stage a copy.
    """
    data=bytearray(Path(path).read_bytes())
    if data[:6]!=b"\x7fELF\x02\x01":
        raise ValueError(f"unsupported ELF format: {path}")
    phoff=struct.unpack_from("<Q",data,32)[0]
    stride,count=struct.unpack_from("<HH",data,54)
    segments=[struct.unpack_from("<IIQQQQQQ",data,phoff+i*stride) for i in range(count)]
    dynamic=next((p for p in segments if p[0]==2),None)
    if dynamic is None:
        raise ValueError(f"ELF has no dynamic section: {path}")
    entries=[]
    for offset in range(dynamic[2],dynamic[2]+dynamic[5],16):
        tag,value=struct.unpack_from("<qQ",data,offset)
        entries.append((offset,tag,value))
        if tag==0:
            break
    address=next(v for _,t,v in entries if t==5)
    segment=next(p for p in segments if p[0]==1 and p[3]<=address<p[3]+p[5])
    strings=segment[2]+address-segment[3]
    paths=[(o,v) for o,t,v in entries if t in (15,29)]
    if len(paths)!=1:
        raise ValueError(f"expected one existing RPATH/RUNPATH: {path}")
    entry,index=paths[0]
    start=strings+index
    end=data.index(0,start)
    encoded=replacement.encode()
    if len(encoded)>end-start:
        raise ValueError(f"ELF path slot too small: {path}")
    # Do not overwrite a shared suffix referenced by another dynamic string.
    for _,tag,value in entries:
        if tag in (1,14) and index<=value<=end-strings:
            raise ValueError(f"ELF path overlaps another dynamic string: {path}")
    data[start:end]=encoded+b"\0"*(end-start-len(encoded))
    struct.pack_into("<q",data,entry,15)
    Path(path).write_bytes(data)


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_wheel(stage, output, name, version, tag, *, requires=(), original=None):
    normalized=canonicalize_name(name).replace("-","_")
    dist=stage/f"{normalized}-{version}.dist-info"
    dist.mkdir(exist_ok=True)
    if original is not None:
        (dist/"METADATA").write_text(original)
    else:
        text=f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
        text+="".join(f"Requires-Dist: {value}\n" for value in requires)
        (dist/"METADATA").write_text(text+"\n")
    (dist/"WHEEL").write_text("Wheel-Version: 1.0\nGenerator: robot_mapping.runtime_bundle\n"
        +f"Root-Is-Purelib: {'true' if tag.endswith('none-any') else 'false'}\n"
        +"".join(f"Tag: {value}\n" for value in expand_tag(tag)))
    record=io.StringIO()
    writer=csv.writer(record,lineterminator="\n")
    path=output/f"{normalized}-{version}-{tag}.whl"
    with zipfile.ZipFile(path,"w",compression=zipfile.ZIP_DEFLATED,compresslevel=6) as wheel:
        for source in sorted(stage.rglob("*")):
            if not source.is_file():
                continue
            relative=source.relative_to(stage).as_posix()
            if source.name in ("RECORD","RECORD.jws","RECORD.p7s"):
                continue
            payload=source.read_bytes()
            digest=base64.urlsafe_b64encode(hashlib.sha256(payload).digest()).rstrip(b"=").decode()
            wheel.writestr(relative,payload)
            writer.writerow((relative,"sha256="+digest,len(payload)))
        relative=f"{dist.name}/RECORD"
        writer.writerow((relative,"",""))
        wheel.writestr(relative,record.getvalue())
    return path


def expand_tag(tag):
    python,abi,system=tag.split("-")
    return [f"{p}-{a}-{s}" for p in python.split(".") for a in abi.split(".") for s in system.split(".")]


def installed_stage(distribution, stage):
    base=Path(distribution.locate_file("")).resolve()
    skipped={"INSTALLER","REQUESTED","direct_url.json","uv_cache.json","RECORD","RECORD.jws","RECORD.p7s"}
    copied=0
    for relative in distribution.files or ():
        source=Path(distribution.locate_file(relative)).resolve()
        # Console entry points are regenerated by pip. Do not copy files from
        # outside site-packages or executable editable-install path hooks.
        if (not source.is_relative_to(base) or not source.is_file() or source.suffix in (".pyc",".pth")
                or source.name in skipped or "__pycache__" in source.parts):
            continue
        target=stage/str(relative)
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(source,target)
        copied+=1
    if not copied:
        raise ValueError(f"no installed wheel files: {distribution.metadata['Name']}")


def distribution_tag(distribution):
    tags=Parser().parsestr(distribution.read_text("WHEEL")).get_all("Tag")
    columns=[sorted(set(t.split("-")[i] for t in tags)) for i in range(3)]
    return "-".join(".".join(values) for values in columns)


def strip_native(stage):
    strip=shutil.which("strip") or shutil.which(platform.machine()+"-linux-gnu-strip")
    if strip is None:
        raise RuntimeError("binutils strip is needed to stage native wheels")
    for path in stage.rglob("*"):
        if path.is_file() and ".so" in path.name:
            subprocess.run([strip,"--strip-debug",str(path)],check=True)


def native_tag():
    python=f"cp{sys.version_info.major}{sys.version_info.minor}"
    return f"{python}-{python}-linux_{platform.machine()}"


def package_gtsam(prefix, stage, output):
    site=prefix/f"lib/python{sys.version_info.major}.{sys.version_info.minor}/site-packages"
    distribution=next(d for d in metadata.distributions(path=[str(site)])
                      if canonicalize_name(d.metadata["Name"])=="gtsam")
    if distribution.version!="4.2.2":
        raise ValueError("only the verified GTSAM 4.2.2 build is supported")
    installed_stage(distribution,stage)
    for library in ("libgtsam.so.4","libgtsam_unstable.so.4","libmetis-gtsam.so"):
        shutil.copy2(prefix/"lib"/library,stage/"gtsam"/library)
    for path in (stage/"gtsam").glob("gtsam*.so"):
        patch_rpath(path,"$ORIGIN")
    for path in (stage/"gtsam_unstable").glob("gtsam_unstable*.so"):
        patch_rpath(path,"$ORIGIN/../gtsam")
    license_file=prefix/"src/gtsam/LICENSE.BSD"
    shutil.copy2(license_file,stage/f"gtsam-{distribution.version}.dist-info/LICENSE.BSD")
    shutil.copy2(prefix/"src/gtsam/gtsam/3rdparty/metis/LICENSE.txt",
                 stage/f"gtsam-{distribution.version}.dist-info/LICENSE.metis.txt")
    strip_native(stage)
    return write_wheel(stage,output,"gtsam",distribution.version,native_tag(),original=distribution.read_text("METADATA"))


def package_vgicp(prefix, stage, output):
    source=prefix/"src/fast_gicp"
    revision=subprocess.check_output(["git","-C",str(source),"rev-parse","HEAD"],text=True).strip()
    if revision!="0e7ec1441c99f7be453db2ea216d5de029387417":
        raise ValueError("unverified fast_gicp revision")
    site=prefix/f"lib/python{sys.version_info.major}.{sys.version_info.minor}/site-packages"
    modules=list(site.glob("pygicp*.so"))
    if len(modules)!=1:
        raise ValueError("expected exactly one compiled pygicp extension")
    shutil.copy2(modules[0],stage/modules[0].name)
    patch_rpath(stage/modules[0].name,"$ORIGIN/")
    shutil.copy2(prefix/"lib/libfast_gicp.so",stage/"libfast_gicp.so")
    version="0.0.1+mapping.1"
    info=stage/f"pygicp-{version}.dist-info"
    info.mkdir()
    shutil.copy2(source/"LICENSE",info/"LICENSE")
    (info/"BUILD.json").write_text(json.dumps({"revision":revision,"patch":"convergence/GIL"},indent=2)+"\n")
    strip_native(stage)
    return write_wheel(stage,output,"pygicp",version,native_tag(),requires=("numpy>=1.26.4,<2",))


def package_fastlio(root, stage, output):
    shutil.copytree(root/"src/fastlio2",stage/"fastlio2",ignore=shutil.ignore_patterns("__pycache__","*.pyc"))
    modules=list((stage/"fastlio2").glob("_fastlio2*.so"))
    if len(modules)!=1:
        raise ValueError("expected an existing native FAST-LIO2 build")
    info=stage/"fastlio2-0.1.0.dist-info"
    info.mkdir()
    shutil.copy2(root/"third_party/fast_lio/ORIGIN.txt",info/"ALGORITHM_ORIGIN.txt")
    strip_native(stage)
    return write_wheel(stage,output,"fastlio2","0.1.0",native_tag(),requires=("numpy>=1.26.4,<2",))


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-prefix",type=Path,required=True)
    parser.add_argument("--fastlio2-root",type=Path,required=True)
    parser.add_argument("--gdk-root",type=Path)
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args(argv)
    output=args.output.resolve()
    output.mkdir(parents=True,exist_ok=False)
    prefix=args.native_prefix.resolve()
    site=prefix/f"lib/python{sys.version_info.major}.{sys.version_info.minor}/site-packages"
    private={canonicalize_name(d.metadata["Name"]):d for d in metadata.distributions(path=[str(site)])}
    root=Path(__file__).resolve().parents[1]
    projects=[root]+([args.gdk_root.resolve()] if args.gdk_root else [])
    for project in projects:
        subprocess.run([sys.executable,"-m","pip","wheel","--no-index","--no-deps",
            "--no-build-isolation","--wheel-dir",str(output),str(project)],check=True)
    with tempfile.TemporaryDirectory(prefix="mapping-wheel-stage-",dir=output) as temporary:
        stage_root=Path(temporary)
        for name,pack in (("gtsam",lambda s:package_gtsam(prefix,s,output)),
                          ("pygicp",lambda s:package_vgicp(prefix,s,output)),
                          ("fastlio2",lambda s:package_fastlio(args.fastlio2_root.resolve(),s,output))):
            stage=stage_root/name
            stage.mkdir()
            pack(stage)
        queue=["numpy==1.26.4","scipy","matplotlib","Pillow","PyYAML","pytest","setuptools","wheel","pybind11"]
        visited=set()
        while queue:
            requirement=Requirement(queue.pop())
            if requirement.marker and not requirement.marker.evaluate({"extra":""}):
                continue
            name=canonicalize_name(requirement.name)
            if name in visited:
                continue
            distribution=private.get(name) if name=="numpy" else None
            distribution=distribution or metadata.distribution(name)
            if requirement.specifier and distribution.version not in requirement.specifier:
                raise ValueError(f"installed dependency does not satisfy {requirement}: {distribution.version}")
            visited.add(name)
            queue.extend(distribution.requires or ())
            stage=stage_root/name
            stage.mkdir()
            installed_stage(distribution,stage)
            write_wheel(stage,output,distribution.metadata["Name"],distribution.version,
                distribution_tag(distribution),original=distribution.read_text("METADATA"))
            shutil.rmtree(stage)
    write_manifest(output,{"native_prefix":str(prefix),"fastlio2_root":str(args.fastlio2_root.resolve())})


def write_manifest(output, provenance):
    entries=[]
    for wheel in sorted(output.glob("*.whl")):
        with zipfile.ZipFile(wheel) as archive:
            infos=[n for n in archive.namelist() if n.count("/")==1 and n.endswith(".dist-info/METADATA")]
            if len(infos)!=1:
                raise ValueError(f"expected one top-level wheel metadata directory: {wheel}")
            info=infos[0]
            package=Parser().parsestr(archive.read(info).decode())
        entries.append({"name":package["Name"],"version":package["Version"],
                        "file":wheel.name,"sha256":sha256(wheel)})
    lock="".join(f"{e['name']}=={e['version']} --hash=sha256:{e['sha256']}\n" for e in entries)
    (output/"requirements.lock").write_text(lock)
    manifest={"format_version":1,"complete":True,"python":platform.python_version(),
        "soabi":sysconfig.get_config_var("SOABI"),"machine":platform.machine(),
        "system":platform.system(),"libc":platform.libc_ver(),"os_release":platform.freedesktop_os_release(),
        "requirements_sha256":sha256(output/"requirements.lock"),"wheels":entries,
        "provenance":provenance,
        "scope":"Restores this verified ABI/OS runtime; OS PCL/Boost libraries and SDK/models are external."}
    (output/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print(f"Exported {len(entries)} locked wheels: {output}")


if __name__=="__main__":
    main()
